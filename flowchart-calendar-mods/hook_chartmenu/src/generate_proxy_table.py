#!/usr/bin/env python3
"""Generate the small runtime lookup table used by the WINMM prototype.

The shipped game never reads the JSON proxy map.  This generator converts the
Hangul rows of that build-time map into a C++ header so the prototype can map
committed Korean IME bytes to the exact CP932 carrier bytes used by the FNL.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--proxy-map", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    document = json.loads(args.proxy_map.read_text(encoding="utf-8-sig"))
    rows: list[tuple[int, int, int, int]] = []
    seen_cp949: set[int] = set()
    seen_unicode: set[int] = set()

    for record in document.get("mapping", []):
        character = record.get("unicode_character")
        if not isinstance(character, str) or len(character) != 1:
            continue
        codepoint = ord(character)
        if not 0xAC00 <= codepoint <= 0xD7A3:
            continue

        cp949 = character.encode("cp949")
        if len(cp949) != 2:
            raise ValueError(f"Expected two CP949 bytes for {character!r}")

        proxy_hex = record.get("proxy_sjis_hex")
        if isinstance(proxy_hex, str):
            cp932 = bytes.fromhex(proxy_hex)
        else:
            proxy_character = record.get("proxy_character")
            if not isinstance(proxy_character, str) or len(proxy_character) != 1:
                raise ValueError(f"Missing proxy character for {character!r}")
            cp932 = proxy_character.encode("cp932")
        if len(cp932) != 2:
            raise ValueError(f"Expected two CP932 proxy bytes for {character!r}")

        proxy_wide = cp932.decode("cp932")
        if len(proxy_wide) != 1:
            raise ValueError(f"Proxy did not decode to one character for {character!r}")

        cp949_packed = (cp949[0] << 8) | cp949[1]
        cp932_packed = (cp932[0] << 8) | cp932[1]
        if cp949_packed in seen_cp949 or codepoint in seen_unicode:
            raise ValueError(f"Duplicate Hangul proxy row for {character!r}")
        seen_cp949.add(cp949_packed)
        seen_unicode.add(codepoint)
        rows.append((cp949_packed, codepoint, cp932_packed, ord(proxy_wide)))

    rows.sort()
    lines = [
        "// Generated by generate_proxy_table.py; do not edit by hand.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "struct HangulProxyRow {",
        "    std::uint16_t cp949_packed;  // lead byte in the high byte",
        "    std::uint16_t unicode_codepoint;",
        "    std::uint16_t cp932_packed;  // lead byte in the high byte",
        "    wchar_t proxy_wchar;",
        "};",
        "",
        "static constexpr HangulProxyRow kHangulProxyRows[] = {",
    ]
    for cp949, codepoint, cp932, proxy_wchar in rows:
        lines.append(
            f"    {{0x{cp949:04X}, 0x{codepoint:04X}, 0x{cp932:04X}, "
            f"static_cast<wchar_t>(0x{proxy_wchar:04X})}},"
        )
    lines.extend(
        [
            "};",
            "",
            "static constexpr std::size_t kHangulProxyRowCount =",
            "    sizeof(kHangulProxyRows) / sizeof(kHangulProxyRows[0]);",
            "",
        ]
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(
        json.dumps(
            {
                "proxy_map": str(args.proxy_map.resolve()),
                "output": str(args.output.resolve()),
                "hangul_rows": len(rows),
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
