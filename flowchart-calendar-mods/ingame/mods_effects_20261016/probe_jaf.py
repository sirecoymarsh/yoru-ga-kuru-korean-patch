    c.append(f'L_Calendar::SetRemainTime({o.get("remain", 400)});')
    c.append(f'KR_SetTrap({"true" if o.get("trap") else "false"});')
    c.append(f'KR_SetRoute({"true" if o.get("route") else "false"});')
